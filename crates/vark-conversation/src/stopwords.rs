#[cfg(test)]
mod tests {
    use super::contains;

    #[test]
    fn negative_words_are_preserved_while_explicit_stopwords_are_filtered() {
        for negation in ["tidak", "bukan", "belum", "tanpa", "not", "no", "never"] {
            assert!(!contains(negation));
        }
        for stopword in ["yang", "dan", "di", "the", "a", "of"] {
            assert!(contains(stopword));
        }
    }
}
